using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Sudzekai.LinCtrl.Assembly.Generator;

[Generator(LanguageNames.CSharp)]
public class AssemblyHostGenerator : IIncrementalGenerator
{
    private const string _attributeFullName =
        "Sudzekai.LinCtrl.Assembly.PluginAssemblyAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var assemblies = context.SyntaxProvider.ForAttributeWithMetadataName(
            _attributeFullName, 
            (node, _) => node is ClassDeclarationSyntax c,
            Transform)
            .Where(static m => m is not null)
            .Select(static (m, _) => m!.Value)
            .Where(static m => m.ImplementsIPluginAssembly);
        
        var allAssemblies = assemblies.Collect();

        context.RegisterSourceOutput(assemblies, static (spc, m) =>
        {
            if (!m.IsPartial)
            {
                spc.ReportDiagnostic(Diagnostic.Create(
                    new("AHG001", ""), Location.None, m.FullTypeName));
                return;
            }
            
            var src = GeneratePartial(m);
            spc.AddSource($"{m.FullTypeName}.Plugin.g.cs", src);
        });
    }

    private static PluginAssemblyModel? Transform(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol type)
            return null;
        
        bool isPartial = type.DeclaringSyntaxReferences
            .Select(r => r.GetSyntax(ct))
            .OfType<ClassDeclarationSyntax>()
            .Any(c => c.Modifiers.Any(Microsoft.CodeAnalysis.CSharp.SyntaxKind.PartialKeyword));

        bool isPublic = type.DeclaredAccessibility == Accessibility.Public;

        bool isImplementsInterface = type.AllInterfaces.Any(i =>
            i.ToDisplayString() == "Sudzekai.LinCtrl.Core.IPluginAssembly");

        string? assemblyTypeName = null;

        if (ctx.Attributes.Length > 0 &&
            ctx.Attributes[0].ConstructorArguments.Length > 0)
        {
            var arg = ctx.Attributes[0].ConstructorArguments[0];
            if (arg.Kind == TypedConstantKind.Type && arg.Value is INamedTypeSymbol t)
                assemblyTypeName = t.ToDisplayString();
        }

           return new PluginAssemblyModel(
                TypeName: type.Name,
                FullTypeName: type.ToDisplayString(),
                Namespace: type.ContainingNamespace.IsGlobalNamespace
                    ? null
                    : type.ContainingNamespace.ToDisplayString(),
                IsPartial: isPartial,
                IsPublic: isPublic,
                ImplementsIPluginAssembly: isImplementsInterface);
    }

    private static string GeneratePartial(PluginAssemblyModel m)
        => $$"""
        // <auto-generated/>
        #nullable enable

        namespace {{m.Namespace}};

        {{(m.IsPublic ? "public" : "internal")}} partial class {{m.TypeName}} 
        {
            private static global:Sudzekai.LinCtrl.Assembly.AssemblyContext _ctx = default!;
            private static global:Sudzekai.LinCtrl.Assembly.AssemblyHostBuilder _builder = default!;
            private static global:Sudzekai.LinCtrl.Assembly.AssemblyHost _host = default!;

            public static {{m.TypeName}} Instance = new {{m.TypeName}}();

            [UnmanagedCallersOnly(EntryPoint = global:Sudzekai.LinCtrl.Core.AssemblyExports.ExchangeVTables)]
            public static unsafe int Exchange(
                global:Sudzekai.LinCtrl.Core.HostVTableDescriptor* hostVTable, 
                global:Sudzekai.LinCtrl.Core.AssemblyVTableDescriptor** assemblyVTable)
            {

            }

            private static int Init() 
            {
                try 
                {
                    _builder = new(_ctx);
                    Instance.ConfigureBuilder(_builder);
                    return 0;
                }
                catch 
                {
                    return 1;
                }
            }

            private static int DelegateLogging(global:Sudzekai.LinCtrl.Core.LogDelegate del)
                => _builder.DelegateLogging(del);

            private static int Build()
            {
                _host = _builder.Build();

                return 0;
            }

            private static IHttpRequestHandler[] GetHandlers()
                => _host.GetHandlers();
        }
        """;
        
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");

        if (m.Namespace is not null)
        {
            sb.AppendLine($"namespace {m.Namespace};");
            sb.AppendLine();
        }

        var access = m.IsPublic ? "public" : "internal";

        sb.AppendLine($"{access} partial class {m.TypeName}");
        sb.AppendLine("{");

        sb.AppendLine("    /// <summary>Единственный экземпляр плагина.</summary>");
        sb.AppendLine($"    public static {m.TypeName} Instance {{ get; }} = new {m.TypeName}();");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>Применяет конфигурацию плагина к builder.</summary>");
        sb.AppendLine("    public static void Register(global::Sudzekai.LinCtrl.Core.AssemblyHostBuilder builder)");
        sb.AppendLine($"        => Instance.ConfigureBuilder(builder);");

        sb.AppendLine("}");
        return sb.ToString();
    }
}
